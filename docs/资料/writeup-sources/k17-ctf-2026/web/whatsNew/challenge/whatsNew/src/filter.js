const BLOCKED_PATTERNS = [
  /on[a-z0-9_-]+/i,
  /\\[xu0-7]/i,
  /%[0-9a-f]{2}/i,
  /[\t\f\v]/,
  /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/
];

const NAMED_ENTITIES = {
  amp: '&',
  apos: "'",
  gt: '>',
  lt: '<',
  quot: '"'
};

function decodeHtml(value) {
  return String(value ?? '').replace(/&(#x[0-9a-f]+|#[0-9]+|[a-z]+);/gi, (match, entity) => {
    if (entity[0] === '#') {
      const base = entity[1].toLowerCase() === 'x' ? 16 : 10;
      const codePoint = Number.parseInt(entity.slice(base === 16 ? 2 : 1), base);
      return Number.isFinite(codePoint) && codePoint >= 0 && codePoint <= 0x10ffff
        ? String.fromCodePoint(codePoint)
        : match;
    }

    return NAMED_ENTITIES[entity.toLowerCase()] || match;
  });
}

function values(input) {
  if (input == null) return [];
  if (Array.isArray(input)) return input.flatMap(values);
  if (typeof input === 'object') return Object.values(input).flatMap(values);
  return [String(input)];
}

function isSuspicious(input) {
  return values(input).some((value) => {
    const normalized = String(value ?? '').toLowerCase();
    return BLOCKED.some((word) => normalized.includes(word)) ||
      BLOCKED_PATTERNS.some((pattern) => pattern.test(normalized));
  });
}

